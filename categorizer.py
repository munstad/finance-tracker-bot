"""
categorizer.py — простая автоматическая категоризация трат по ключевым словам.

Это не "настоящий" ML/NLP, а быстрый практичный вариант: словарь
"ключевое слово -> категория". Его легко расширять под себя.
Если ни одно слово не подошло — категория "Прочее".
"""

CATEGORY_KEYWORDS = {
    "Еда": [
        "кофе", "обед", "ужин", "завтрак", "продукты", "магазин",
        "пятерочка", "перекресток", "вкусвилл", "ресторан", "кафе",
        "пицца", "суши", "макдональдс", "бургер",
    ],
    "Транспорт": [
        "такси", "метро", "автобус", "бензин", "заправка", "яндекс go",
        "каршеринг", "парковка", "билет",
    ],
    "Развлечения": [
        "кино", "театр", "концерт", "игра", "steam", "подписка",
        "netflix", "spotify", "бар", "клуб",
    ],
    "Здоровье": [
        "аптека", "врач", "лекарства", "стоматолог", "больница", "анализы",
    ],
    "Одежда": [
        "одежда", "обувь", "куртка", "футболка", "джинсы", "zara", "h&m",
    ],
    "Жильё": [
        "аренда", "квартира", "коммуналка", "интернет", "связь", "жкх",
    ],
}


def detect_category(text: str) -> str:
    """
    Ищет в тексте ключевые слова и возвращает первую подходящую категорию.
    Текст приводится к нижнему регистру, чтобы не зависеть от регистра ввода.
    """
    text_lower = text.lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        for word in keywords:
            if word in text_lower:
                return category
    return "Прочее"
